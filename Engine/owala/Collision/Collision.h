#pragma once
#include "Vector2D.h"
#include "Entity.h"
#include "AABB_Collision.h" // NEW: Includes the low-level functions

namespace Framework {

    /**
     * @enum CollisionState
     * @brief Describes the current collision status between two objects.
     */
    enum class CollisionState {
        NoCollision, // Objects are not touching and not on a collision course this frame.
        Overlapping, // Objects are currently penetrating each other.
        Separating,  // Objects are touching but moving away from each other.
        WillCollide  // Objects are not touching but are on a collision course this frame.
    };

    /**
     * @struct Contact
     * @brief Holds all information about a resolved collision between two entities.
     * @details This is often called a "contact manifold". It's generated by the
     * physics system after a collision is detected and resolved.
     */
    struct Contact {
        Entity A;
        Entity B;
        CollisionState State;
    };

} // namespace Framework